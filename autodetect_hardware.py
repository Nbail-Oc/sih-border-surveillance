def main():
    print("=" * 65)
    print("[*] IBVAP HARDWARE PROFILER - SYSTEM ADAPTATION SCAN")
    print("=" * 65)

    gpus = detect_nvidia_gpu()
    cpu = detect_cpu_specs()

    print(f"[*] CPU Cores:   {cpu['cores']}")
    print(f"[*] Platform:    {cpu['platform']}")
    if gpus:
        print(f"[+] GPUs Found:  {len(gpus)}")
        for i, g in enumerate(gpus):
            print(f"    - GPU {i}: {g['name']} | {g['vram_mb']} MB VRAM | Driver: {g['driver']}")
    else:
        print(f"[-] GPUs Found:  None (Running in CPU Edge Mode)")

    profile = determine_tier(gpus, cpu)
    print("-" * 65)
    print(f"[*] OPTIMAL CONFIGURATION: {profile['name']}")
    print(f"[*] Info: {profile['description']}")
    print(f"    - AI Model:    {profile['model_path']}")
    print(f"    - Input Res:   {profile['model_size']}x{profile['model_size']}")
    print(f"    - Hardware:    {profile['detector_device']}")
    print(f"    - Detect FPS:  {profile['detect_fps']} FPS")
    print("-" * 65)

    if "--apply" in sys.argv or "-a" in sys.argv:
        # Backup existing config
        if os.path.exists(TARGET_CONFIG):
            backup_path = TARGET_CONFIG + ".bak"
            shutil.copyfile(TARGET_CONFIG, backup_path)
            print(f"[*] Backed up current config to {backup_path}")

        new_config_text = generate_config(profile)
        with open(TARGET_CONFIG, "w", encoding="utf-8") as f:
            f.write(new_config_text)
        print(f"[+] Successfully applied optimal config to {TARGET_CONFIG}!")
    else:
        print("[!] Dry-run complete. To automatically apply this config to config.yml, run:")
        print("    python autodetect_hardware.py --apply")

if __name__ == "__main__":
    main()
