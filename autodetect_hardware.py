"""
IBVAP - Intelligent Hardware Auto-Profiler & Config Generator
Detects the host machine's hardware capabilities (CPU cores, RAM, NVIDIA GPU/VRAM)
and automatically selects and applies the optimal 3-Tier Frigate configuration.

Usage:
  python autodetect_hardware.py [--apply] [--dry-run]
"""

import os
import sys
import shutil
import subprocess
import json
import platform

REPO_ROOT = os.path.abspath(os.path.dirname(__file__))
CONFIG_DIR = os.path.join(REPO_ROOT, "config")
TARGET_CONFIG = os.path.join(CONFIG_DIR, "config.yml")

def detect_nvidia_gpu():
    """Detect NVIDIA GPU availability, model name, and VRAM in MB."""
    try:
        cmd = [
            "nvidia-smi",
            "--query-gpu=name,memory.total,driver_version",
            "--format=csv,noheader,nounits"
        ]
        out = subprocess.check_output(cmd, stderr=subprocess.DEVNULL, text=True).strip()
        if out:
            lines = out.splitlines()
            gpus = []
            for line in lines:
                parts = [p.strip() for p in line.split(',')]
                if len(parts) >= 2:
                    name = parts[0]
                    vram_mb = int(parts[1])
                    driver = parts[2] if len(parts) > 2 else "Unknown"
                    gpus.append({"name": name, "vram_mb": vram_mb, "driver": driver})
            return gpus
    except Exception:
        pass
    return []

def detect_cpu_specs():
    """Detect CPU name and physical core count."""
    cpu_info = {
        "cores": os.cpu_count() or 4,
        "platform": platform.platform(),
        "processor": platform.processor()
    }
    return cpu_info

def determine_tier(gpus, cpu):
    """
    Classify system into Tier 1 (CPU / Edge), Tier 2 (Mid GPU), or Tier 3 (High GPU).
    """
    if not gpus:
        return {
            "tier": 1,
            "name": "Tier 1: Low / Edge CPU (Intel i3 / Outpost Laptop)",
            "detector_device": "AUTO",
            "model_path": "/config/model_cache/yolov8n.onnx",
            "model_type": "yolo-generic",
            "model_size": 320,
            "detect_fps": 5,
            "description": "No dedicated NVIDIA GPU detected. Using OpenVINO CPU acceleration with YOLOv8n (320x320) at 5 FPS."
        }

    # Evaluate highest VRAM GPU
    max_vram = max(g["vram_mb"] for g in gpus)
    gpu_name = gpus[0]["name"]

    if max_vram >= 16000:
        return {
            "tier": 3,
            "name": "Tier 3: High / Enterprise Server (RTX 4090 / A5000 / Server)",
            "detector_device": "GPU",
            "model_path": "/config/model_cache/dfine_x.onnx",
            "model_type": "dfine",
            "model_size": 640,
            "detect_fps": 20,
            "description": f"Detected high-end GPU: {gpu_name} ({max_vram} MB VRAM). Using TensorRT with D-FINE Extra-Large (640x640) at 20 FPS."
        }
    else:
        return {
            "tier": 2,
            "name": "Tier 2: Medium / Workstation (RTX 2060/3050/3060 / Laptop GPU)",
            "detector_device": "GPU",
            "model_path": "/config/model_cache/yolov8s.onnx",
            "model_type": "yolo-generic",
            "model_size": 640,
            "detect_fps": 10,
            "description": f"Detected workstation/laptop GPU: {gpu_name} ({max_vram} MB VRAM). Using TensorRT/CUDA with YOLOv8s (640x640) at 10 FPS."
        }

